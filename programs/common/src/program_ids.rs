//! Program ID getters for all MGK programs.
//!
//! Returns canonical program addresses for CPI callers.

use pinocchio::pubkey::Pubkey;

const PERPS_CORE_ID: Pubkey = [
    0xa5, 0x37, 0x22, 0x28, 0xac, 0x17, 0xdf, 0x65, 0x2d, 0x17, 0x84, 0x90, 0x33, 0x8a, 0xaa, 0xbe,
    0xbf, 0x62, 0xae, 0x34, 0x2b, 0x47, 0x90, 0xc2, 0xdb, 0xa6, 0x7a, 0x63, 0x78, 0xd6, 0xd9, 0xad,
];

const PERPS_MATCHER_ID: Pubkey = [
    0x60, 0xc2, 0xf7, 0x2a, 0x54, 0x2e, 0xb6, 0xc9, 0xa9, 0x7e, 0xfa, 0x39, 0x6a, 0x57, 0xea, 0x2d,
    0x64, 0x59, 0x12, 0xe4, 0xb6, 0x6c, 0xdb, 0x8c, 0x29, 0x4d, 0x85, 0xfa, 0xaf, 0x90, 0x52, 0x8d,
];

const ORACLE_ID: Pubkey = [
    0xb0, 0x5c, 0xcf, 0x41, 0x1d, 0x0f, 0xe2, 0x1f, 0x4f, 0xc7, 0x3c, 0x55, 0xf5, 0xcb, 0x78, 0x2f,
    0x0f, 0xca, 0x0a, 0x9e, 0x9f, 0x5c, 0x49, 0x07, 0x43, 0x10, 0xc9, 0xb9, 0x2a, 0x46, 0xc0, 0xb8,
];

#[inline]
pub fn perps_core_program_id() -> Pubkey {
    PERPS_CORE_ID
}

#[inline]
pub fn perps_matcher_program_id() -> Pubkey {
    PERPS_MATCHER_ID
}

#[inline]
pub fn mgk_oracle_program_id() -> Pubkey {
    ORACLE_ID
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_program_ids_are_not_zero() {
        let zero = [0u8; 32];
        assert_ne!(
            perps_core_program_id(),
            zero,
            "perps_core_program_id must not be zero"
        );
        assert_ne!(
            perps_matcher_program_id(),
            zero,
            "perps_matcher_program_id must not be zero"
        );
        assert_ne!(
            mgk_oracle_program_id(),
            zero,
            "mgk_oracle_program_id must not be zero"
        );
    }
}
